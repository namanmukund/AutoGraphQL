const userData = async (email, phone, studentName, grade) => {
  let filter = '';
  const childIds = [];
  if (!get(phone, 'countryCode') || !get(phone, 'number')) {
    filter = `
      {email:"${email.trim()
    .toLowerCase()}"}
    `;
  } else {
    const { countryCode, number } = phone;
    filter = `{
      or:[
      {email:"${email.trim()
    .toLowerCase()}"}
      {and:[
        {phone_countryCode_subDoc:"${countryCode}"}
        {phone_number_subDoc: "${number}"}
      ]}
      ]
    }`;
  }
  const query = `
  query {
    users(filter: ${filter}){
      id
      name
      email
      phone {
      countryCode
      number
      }
      parentProfile {
        id
        children {
        id 
        user{
          id
          name
          role
        }
      }
    }
  }
}
  `;
  const res = get(await callLocalGraphqlApi(query), 'data.users', []);
  if (res && res.length) {
    const children = get(res[0], 'parentProfile.children', []);
    if (children && children.length) {
      children.forEach((child) => {
        childIds.push(child.user.id);
      });
    }
  } else {
    const pcQuery = `mutation parentChildSignUp($input: ParentChildSignUpInput) {
  parentChildSignUp(input: $input) {
    id
    name
    children {
      id
      name
    }
   }
}
`;
    const variables = {
      input: {
        parentName: 'Parent',
        childName: studentName,
        parentEmail: email,
        parentPhone: phone,
        grade: `Grade${grade}`,
        country: 'india',
        timezone: 'Asia/Kolkata',
        utmSource: 'RadioStreet',
        utmCampaign: 'Spy Squad Camp - 24th Oct',
      },
    };
    await callLocalGraphqlApi(pcQuery, '', variables);
  }
  return childIds;
};

const getEventAttendees = async () => {
  let childrenIds = [];
  // eslint-disable-next-line no-restricted-syntax
  for (const attendee of attendeesData) {
    const {
      number, email, studentName, grade,
    } = attendee;
    if (number || email) {
      const pn = number.toString();
      const phone = {
        countryCode: '+91',
        number: pn,
      };
      // eslint-disable-next-line no-await-in-loop
      const userId = await userData(email, phone, studentName, grade);
      childrenIds = [...childrenIds, ...userId];
    }
  }
};

